/** Паспорта оборудования ПУЛЬСТОК
 *  Гармонические профили и технические характеристики
 *  для каждой категории оборудования объектов мониторинга.
 */

export interface HarmonicLine {
  order: number;   // порядок гармоники (2, 3, 4 … 13)
  label: string;   // «2-я», «3-я» и т.д.
  percent: number; // доля от первой гармоники, %
}

export interface EquipmentPassport {
  category: string;
  label: string;
  description: string;
  specs: { key: string; value: string }[];
  thd: number;            // THD в %
  harmonics: HarmonicLine[];
  notes: string;
}

const h = (order: number, percent: number): HarmonicLine => ({
  order,
  label: `${order}-я`,
  percent,
});

